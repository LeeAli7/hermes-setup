#!/usr/bin/env python3
"""Egress pool manager for the Hermes free-Zen lane.

Sources are local Bun relays, each pinned to one egress identity.  The
forwarder asks for a lease before every upstream attempt and reports the
result afterwards.  Two consecutive 429s on one source put it into cooldown;
a 200 clears the failure streak.

Strictly free: when every source is cooling down the manager returns 503 and
the forwarder surfaces a 429 instead of falling back to a paid provider.
"""
import json
import os
import threading
import time
import urllib.error
import urllib.request
import uuid
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

PORT = int(os.environ.get("EGRESS_POOL_PORT", "9200"))
_EGRESS_HOME = os.environ.get(
    "HERMES_EGRESS_HOME", os.path.expanduser("~/.hermes/ippool"))
STATE_FILE = os.environ.get(
    "EGRESS_POOL_STATE", os.path.join(_EGRESS_HOME, "egress_pool_state.json"))
LEASE_TTL = 180.0
RECHECK_INTERVAL = float(os.environ.get(
    "EGRESS_POOL_RECHECK_INTERVAL", "300"))
# Background probing of higher tiers while a lower tier is serving.  This is
# deliberately a lightweight models-endpoint check, not a chat completion:
# the free Zen quota is per-IP, and a real chat probe would spend the very
# allowance the next user turn needs.  A 200 marks the source "suspect";
# the next real lease is the final quota test.
PROBE_INTERVAL = float(os.environ.get("EGRESS_POOL_PROBE_INTERVAL", "45"))
PROBE_TIMEOUT = float(os.environ.get("EGRESS_POOL_PROBE_TIMEOUT", "8"))
PROBE_PATH = os.environ.get("EGRESS_POOL_PROBE_PATH", "/zen/v1/models")
PROBE_AUTH = os.environ.get("EGRESS_POOL_PROBE_AUTH", "Bearer public")
CLIENT_TTL = 300.0

# VPN-only source list.  Each slot is a separate netns + OpenVPN tunnel +
# Bun relay; the ports and count are generated by install.sh.  No direct host
# IP, no Tor, no Oracle/static IPv6 lanes are ever added here.
_VPN_SLOTS = int(os.environ.get("VPNGATE_SLOTS", "2"))
_RELAY_BASE = int(os.environ.get("VPNGATE_RELAY_PORT_BASE", "9120"))
_DEFAULT_SOURCES = [
    {
        "name": "vpngate" if i == 0 else f"vpngate{i + 1}",
        "relay": f"http://127.0.0.1:{_RELAY_BASE + i}",
        "priority": 0,
    }
    for i in range(max(1, _VPN_SLOTS))
]


def _load_sources():
    raw = os.environ.get("EGRESS_POOL_SOURCES", "").strip()
    if not raw:
        path = os.environ.get("EGRESS_POOL_SOURCES_FILE", "").strip()
        if path:
            try:
                with open(path, encoding="utf-8") as f:
                    raw = f.read().strip()
            except Exception as e:
                print(f"egress-pool: cannot read {path}: {e}", flush=True)
    if raw:
        try:
            data = json.loads(raw)
            if isinstance(data, list) and data:
                return data
        except Exception as e:
            print(f"egress-pool: bad EGRESS_POOL_SOURCES: {e}", flush=True)
    return list(_DEFAULT_SOURCES)

SOURCES = _load_sources()
BY_NAME = {s["name"]: s for s in SOURCES}
LOCK = threading.Lock()
LEASES = {}
# Per-request failover state: which sources were already tried in this request,
# and whether the one forced recheck pass was already used.
CLIENTS = {}


def _fresh_state():
    return {
        "state": "new",
        "fail_streak": 0,
        "cooldown_until": 0.0,
        "success": 0,
        "fail": 0,
        "last_status": None,
        "last_retry_after": None,
        "last_error": None,
        "last_used": 0.0,
        "last_ok": 0.0,
        "recheck_after": 0.0,
    }


STATE = {s["name"]: _fresh_state() for s in SOURCES}


def _now():
    return time.time()


def _load_state():
    try:
        with open(STATE_FILE, encoding="utf-8") as f:
            data = json.load(f)
    except Exception:
        return
    for name, saved in (data.get("sources") or {}).items():
        if name not in STATE:
            continue
        st = STATE[name]
        for key in ("state", "fail_streak", "cooldown_until", "success",
                    "fail", "last_status", "last_retry_after", "last_error",
                    "last_used", "last_ok", "recheck_after"):
            if key in saved:
                st[key] = saved[key]
        if (st["state"] in ("cooldown", "recovering")
                and st["cooldown_until"] <= _now()):
            st["state"] = "new"
            st["fail_streak"] = 0
    print(f"egress-pool: state restored from {STATE_FILE}", flush=True)


def _save_state():
    tmp = STATE_FILE + ".tmp"
    try:
        os.makedirs(os.path.dirname(STATE_FILE), exist_ok=True)
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump({"updated": _now(), "sources": STATE}, f, indent=2)
        os.replace(tmp, STATE_FILE)
    except Exception as e:
        print(f"egress-pool: state save failed: {e}", flush=True)


def _healthy(src):
    st = STATE[src["name"]]
    if not src.get("enabled", True):
        return False
    if st["state"] == "recovering":
        if st["cooldown_until"] > _now():
            return False
        st["state"] = "new"
        st["fail_streak"] = 0
    if st["state"] == "cooldown" and st["cooldown_until"] > _now():
        return False
    if st["state"] == "cooldown":
        st["state"] = "new"
        st["fail_streak"] = 0
    return True


def _priority(src):
    return int(src.get("priority", 100))


def _client_state(client):
    now = _now()
    st = CLIENTS.get(client)
    if not st:
        st = {"tried": set(), "wrapped": False, "last": now}
        CLIENTS[client] = st
    st["last"] = now
    return st


def _prune_clients():
    cutoff = _now() - CLIENT_TTL
    for key, st in list(CLIENTS.items()):
        if st["last"] < cutoff:
            CLIENTS.pop(key, None)


def _pick_recheck(cs, exclude, now, max_priority=None, force=False):
    """Pick a source even if it is cooling down (actual request = probe)."""
    candidates = []
    for s in SOURCES:
        name = s["name"]
        if name in exclude or not s.get("enabled", True):
            continue
        if max_priority is not None and _priority(s) > max_priority:
            continue
        if name in cs["tried"]:
            continue
        st = STATE[name]
        if st["state"] == "recovering":
            if st["cooldown_until"] > now:
                continue
            st["state"] = "new"
            st["fail_streak"] = 0
        if not force and float(st.get("recheck_after") or 0) > now:
            continue
        candidates.append(s)
    if not candidates:
        return None
    candidates.sort(key=lambda s: (_priority(s),
                                   STATE[s["name"]]["last_used"]))
    src = candidates[0]
    cs["tried"].add(src["name"])
    STATE[src["name"]]["recheck_after"] = now + RECHECK_INTERVAL
    return src


def _probe_once():
    """Probe higher-priority sources while a lower one is serving.

    VPN-only build: all slots are priority 0, so this loop normally has no
    candidates.  It is kept for parity with the main pool and for future
    extra tiers; the VPNGate supervisor/recovery own per-slot health.
    """
    now = _now()
    with LOCK:
        healthy = [s for s in SOURCES if _healthy(s)]
        best_prio = min((_priority(s) for s in healthy), default=10 ** 9)
        candidates = []
        for s in SOURCES:
            if not s.get("enabled", True):
                continue
            if _priority(s) >= best_prio:
                continue
            st = STATE[s["name"]]
            if st["state"] in ("ok", "recovering"):
                continue
            if st["state"] == "cooldown":
                left = float(st.get("cooldown_until") or 0) - now
                # A 429 usually needs a fresh IP, not a probe of the same
                # burned address; only retry it near the end of its window.
                if left > 60:
                    continue
            candidates.append(s)
        if not candidates:
            return

    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    for s in candidates:
        url = str(s["relay"]).rstrip("/") + PROBE_PATH
        req = urllib.request.Request(url, headers={
            "Authorization": PROBE_AUTH,
            "User-Agent": "opencode/latest/2.3.0/cli",
            "Accept": "*/*",
        })
        try:
            with opener.open(req, timeout=PROBE_TIMEOUT) as resp:
                status = int(getattr(resp, "status", 0) or 0)
        except urllib.error.HTTPError as e:
            status = int(e.code)
        except Exception:
            status = 0
        with LOCK:
            st = STATE.get(s["name"])
            if not st:
                continue
            if status == 200:
                st["state"] = "suspect"
                st["fail_streak"] = 0
                st["cooldown_until"] = 0.0
                st["last_status"] = 200
                st["last_ok"] = now
                st["last_error"] = "probe models 200"
                print(f"egress-pool: probe {s['name']} 200 -> suspect",
                      flush=True)
            elif status >= 500 or status == 0:
                st["last_status"] = status
                st["last_error"] = f"probe status {status}"
                print(f"egress-pool: probe {s['name']} {status} (dead)",
                      flush=True)
            else:
                print(f"egress-pool: probe {s['name']} {status} (kept state)",
                      flush=True)


def _probe_worker():
    while True:
        try:
            _probe_once()
        except Exception as e:
            print(f"egress-pool: probe loop error: {e}", flush=True)
        time.sleep(max(5.0, PROBE_INTERVAL))


def _choose(prefer, exclude, client=""):
    """Pick the next VPNGate slot, with one recheck pass if all are cooling.

    Returns (source, recheck).  A recheck lease is a cooled-down slot that is
    retried once before returning 503.  The forwarder's real request is the
    probe, so no extra upstream request is spent.
    """
    now = _now()
    cs = _client_state(client or "anonymous")
    healthy = []
    for s in SOURCES:
        if s["name"] in exclude:
            continue
        if _healthy(s):
            healthy.append(s)
    healthy.sort(key=lambda s: (_priority(s),
                                STATE[s["name"]]["last_used"]))
    best = healthy[0] if healthy else None

    if best:
        if prefer:
            for s in healthy:
                if (s["name"] == prefer
                        and _priority(s) == _priority(best)
                        and STATE[s["name"]]["fail_streak"] == 0):
                    return s, False
        return best, False

    # No healthy source: walk the priority list once, including cooldown
    # sources.  While a slot is rotating, prefer a recheck of an existing
    # slot over immediately returning 503.
    if cs["wrapped"]:
        # The single wrap to Tier 1 already failed; do not start a second
        # full cycle in the same request.
        return None, False
    src = _pick_recheck(cs, exclude, now)
    if src:
        return src, True

    # Every slot failed: make one forced recheck before returning 503.
    cs["wrapped"] = True
    cs["tried"].clear()
    top = min((_priority(s) for s in SOURCES
               if s.get("enabled", True)), default=0)
    src = _pick_recheck(cs, exclude, now, max_priority=top, force=True)
    if src:
        return src, True
    return None, False


def _retry_after_seconds(value):
    if value is None or value == "":
        return None
    try:
        return int(float(str(value).strip()))
    except Exception:
        return None


def _snapshot():
    return [
        {"name": s["name"], "relay": s["relay"],
         "priority": s.get("priority", 100), "enabled": s.get("enabled", True),
         "address": s.get("address"),
         **STATE[s["name"]]}
        for s in SOURCES
    ]


def _prune_leases():
    cutoff = _now() - LEASE_TTL
    for lid, lease in list(LEASES.items()):
        if lease["ts"] < cutoff:
            LEASES.pop(lid, None)


def _record(source, status, retry_after=None):
    st = STATE[source]
    st["last_status"] = status
    st["last_retry_after"] = retry_after
    if 200 <= status < 300:
        st["state"] = "ok"
        st["fail_streak"] = 0
        st["cooldown_until"] = 0.0
        st["success"] += 1
        st["last_ok"] = _now()
        st["last_error"] = None
        st["recheck_after"] = 0.0
        return
    if status == 400:
        # Shape/model problem, not an egress burn.  Do not penalise.
        return
    st["fail"] += 1
    # One failed request is enough to move to the next priority.  The old
    # two-strike rule made every burned IP cost two requests.
    st["fail_streak"] += 1
    if status == 429:
        cooldown = max(_retry_after_seconds(retry_after) or 0, 30)
        st["state"] = "cooldown"
        st["cooldown_until"] = _now() + cooldown
        st["last_error"] = f"429 cooldown {cooldown}s"
    else:
        # 0 (timeout/connection), 403, 5xx: relay or IP problem.  A timeout
        # on a large body usually means the exit is too slow; keep it out
        # long enough for the slot recovery timer to rotate it instead of
        # re-leasing the same slow exit a minute later.
        cooldown = 300 if status == 0 else 60
        st["state"] = "cooldown"
        st["cooldown_until"] = _now() + cooldown
        st["last_error"] = f"status {status} cooldown {cooldown}s"
    st["recheck_after"] = _now() + RECHECK_INTERVAL


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, fmt, *args):
        pass

    def _send(self, code, obj):
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _read_json(self):
        try:
            n = int(self.headers.get("Content-Length", 0))
            if n <= 0:
                return {}
            return json.loads(self.rfile.read(n))
        except Exception:
            return {}

    def do_GET(self):
        path = self.path.split("?", 1)[0]
        if path in ("/health", "/sources"):
            with LOCK:
                _prune_leases()
                _prune_clients()
                self._send(200, {"ok": True, "sources": _snapshot(),
                                 "leases": len(LEASES)})
            return
        self._send(404, {"error": "not_found"})

    def do_POST(self):
        path = self.path.split("?", 1)[0]
        body = self._read_json()
        if path == "/lease":
            prefer = body.get("prefer")
            exclude = set(body.get("exclude") or [])
            client = body.get("client") or ""
            with LOCK:
                _prune_leases()
                _prune_clients()
                src, recheck = _choose(prefer, exclude, client)
                if not src:
                    self._send(503, {"error": "no_egress",
                                     "reason": "all_tiers_exhausted",
                                     "sources": _snapshot()})
                    return
                lease_id = uuid.uuid4().hex
                LEASES[lease_id] = {"source": src["name"], "ts": _now(),
                                    "client": client}
                STATE[src["name"]]["last_used"] = _now()
                if recheck:
                    print(f"egress-pool: recheck {src['name']} "
                          f"tier={_priority(src)} "
                          f"client={client[:8]}", flush=True)
                self._send(200, {"lease_id": lease_id, "source": src["name"],
                                 "relay": src["relay"],
                                 "proxy": src.get("proxy"),
                                 "priority": _priority(src),
                                 "recheck": bool(recheck)})
            return
        if path.startswith("/lease/") and path.endswith("/result"):
            lease_id = path[len("/lease/"):-len("/result")]
            with LOCK:
                lease = LEASES.pop(lease_id, None)
                if not lease:
                    self._send(404, {"error": "unknown_lease"})
                    return
                status = int(body.get("status") or 0)
                _record(lease["source"], status, body.get("retry_after"))
                _save_state()
                self._send(200, {"ok": True, "source": lease["source"],
                                 "state": STATE[lease["source"]]})
            return
        if path.startswith("/source/") and path.endswith("/state"):
            name = path[len("/source/"):-len("/state")]
            with LOCK:
                if name not in STATE:
                    self._send(404, {"error": "unknown_source"})
                    return
                st = STATE[name]
                wanted = body.get("state")
                if wanted == "ok":
                    st.update(state="ok", fail_streak=0, cooldown_until=0.0,
                              last_error=None)
                elif wanted == "cooldown":
                    secs = float(body.get("seconds") or 300)
                    st.update(state="cooldown", fail_streak=2,
                              cooldown_until=_now() + secs,
                              last_error=f"admin cooldown {secs:.0f}s")
                elif wanted == "recovering":
                    secs = float(body.get("seconds") or 60)
                    st.update(state="recovering", fail_streak=2,
                              cooldown_until=_now() + secs,
                              last_error="recovery in progress")
                elif wanted == "new":
                    STATE[name] = _fresh_state()
                else:
                    self._send(400, {
                        "error": "state must be ok/cooldown/recovering/new"})
                    return
                _save_state()
                self._send(200, {"ok": True, "source": name,
                                 "state": STATE[name]})
            return
        if path == "/reset":
            with LOCK:
                for name in STATE:
                    STATE[name] = _fresh_state()
                LEASES.clear()
                _save_state()
                self._send(200, {"ok": True, "sources": _snapshot()})
            return
        self._send(404, {"error": "not_found"})


def main():
    _load_state()
    server = ThreadingHTTPServer(("127.0.0.1", PORT), Handler)
    server.daemon_threads = True
    threading.Thread(target=_probe_worker, name="egress-probe",
                     daemon=True).start()
    print(f"egress-pool on 127.0.0.1:{PORT} sources="
          f"{[s['name'] for s in SOURCES]} probe={PROBE_INTERVAL:.0f}s",
          flush=True)
    server.serve_forever()


if __name__ == "__main__":
    main()
