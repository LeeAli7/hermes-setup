#!/usr/bin/env bash
# Install the VPN-only Hermes egress pack on a fresh Linux device.
#
# Run as the Hermes user (the account that runs the gateway/forwarder), NOT as
# root.  The script uses sudo only for the netns/OpenVPN system units.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ETC_DIR="/etc/hermes-egress"
INSTALL_DIR="${HERMES_EGRESS_HOME:-$HOME/.hermes/ippool}"
SLOTS="${VPNGATE_SLOTS:-2}"
PHYS_IF="${VPNGATE_PHYS_IF:-}"
ASSUME_YES=0
NO_START=0
FORCE=0

usage() {
  cat <<'EOF'
usage: ./install.sh [options]

  --slots N       VPNGate tunnels (1-4, default 2)
  --iface IF      physical NIC for OpenVPN (default: default-route NIC)
  --yes           install missing apt packages / Bun without prompting
  --no-start      install units but do not enable/start them
  --force         overwrite an existing /etc/hermes-egress/egress.env
  -h, --help      show this help

Run as the Hermes user; sudo is requested for system units.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --slots) SLOTS="${2:?}"; shift 2 ;;
    --iface) PHYS_IF="${2:?}"; shift 2 ;;
    --yes|-y) ASSUME_YES=1; shift ;;
    --no-start) NO_START=1; shift ;;
    --force) FORCE=1; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown option: $1" >&2; usage; exit 2 ;;
  esac
done

if [[ "$EUID" -eq 0 ]]; then
  echo "Run this script as the Hermes user, not root (it will call sudo)." >&2
  exit 1
fi
if ! [[ "$SLOTS" =~ ^[1-4]$ ]]; then
  echo "--slots must be 1-4 (netns addresses are 10.20<slot>.0.0/24)" >&2
  exit 2
fi
if ! command -v sudo >/dev/null 2>&1; then
  echo "sudo is required for netns/OpenVPN system units." >&2
  exit 1
fi
sudo -v

# ---------- dependencies ----------
missing=()
for c in openvpn iptables curl python3 ip ss; do
  command -v "$c" >/dev/null 2>&1 || missing+=("$c")
done
if ((${#missing[@]})); then
  echo "Missing: ${missing[*]}"
  if [[ "$ASSUME_YES" != "1" ]]; then
    echo "Re-run with --yes to install them with apt-get, or install manually." >&2
    exit 1
  fi
  if command -v apt-get >/dev/null 2>&1; then
    sudo apt-get update
    sudo apt-get install -y openvpn iptables curl python3 iproute2
  else
    echo "No apt-get; install ${missing[*]} manually." >&2
    exit 1
  fi
fi
if [[ ! -c /dev/net/tun ]]; then
  echo "ERROR: /dev/net/tun is missing. Enable TUN/TAP in the VPS panel." >&2
  exit 1
fi

# ---------- Bun ----------
BUN_BIN="${BUN_BIN:-}"
if [[ -z "$BUN_BIN" ]]; then
  if command -v bun >/dev/null 2>&1; then
    BUN_BIN="$(command -v bun)"
  elif [[ -x "$HOME/.bun/bin/bun" ]]; then
    BUN_BIN="$HOME/.bun/bin/bun"
  else
    echo "Bun is not installed."
    if [[ "$ASSUME_YES" != "1" ]]; then
      echo "Re-run with --yes to install Bun from https://bun.sh, or install it manually." >&2
      exit 1
    fi
    curl -fsSL https://bun.sh/install | bash
    BUN_BIN="$HOME/.bun/bin/bun"
  fi
fi
"$BUN_BIN" --version >/dev/null

# ---------- physical interface ----------
if [[ -z "$PHYS_IF" ]]; then
  PHYS_IF="$(ip route show default | awk '/dev/ {print $5; exit}')"
fi
if [[ -z "$PHYS_IF" ]]; then
  echo "Cannot detect the default-route interface; pass --iface." >&2
  exit 1
fi

# ---------- files ----------
mkdir -p "$INSTALL_DIR"
sudo chown -R "$USER:$(id -gn "$USER")" "$INSTALL_DIR" 2>/dev/null || true
# The root tunnel supervisor writes live/results here, while the user-owned
# recovery timer must be able to drop rotate.request into the control dirs.
for ((i = 0; i < SLOTS; i++)); do
  if [[ "$i" == "0" ]]; then
    ctrl="$INSTALL_DIR/vpngate_control"
  else
    ctrl="$INSTALL_DIR/vpngate_control$i"
  fi
  mkdir -p "$ctrl"
  chmod 0775 "$ctrl"
done
install -m 0644 "$HERE"/lib/egress_pool.py \
  "$HERE"/lib/vpngate_tunnel.py \
  "$HERE"/lib/vpngate_recovery.py \
  "$HERE"/lib/netns_connect_proxy.py \
  "$HERE"/lib/bun_relay.ts "$INSTALL_DIR"/
chmod 0755 "$INSTALL_DIR/vpngate_tunnel.py" "$INSTALL_DIR/vpngate_recovery.py"

sudo install -d -m 0755 "$ETC_DIR" /usr/local/share/hermes-egress
sudo install -m 0755 "$HERE/bin/hermes-egress-run" /usr/local/bin/hermes-egress-run
sudo install -m 0755 "$HERE/bin/hermes-egress" /usr/local/bin/hermes-egress
sudo install -m 0644 "$HERE/TZ.md" /usr/local/share/hermes-egress/TZ.md
sudo install -m 0644 "$HERE/README.md" /usr/local/share/hermes-egress/README.md

# ---------- config ----------
if [[ -f "$ETC_DIR/egress.env" && "$FORCE" != "1" ]]; then
  echo "Keeping existing $ETC_DIR/egress.env (use --force to rewrite)."
else
  sudo tee "$ETC_DIR/egress.env" >/dev/null <<EOF
# Generated by vpn-egress/install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
HERMES_EGRESS_HOME=$INSTALL_DIR
VPNGATE_SLOTS=$SLOTS
VPNGATE_RELAY_PORT_BASE=9120
VPNGATE_PROXY_PORT_BASE=8897
VPNGATE_PHYS_IF=$PHYS_IF
EGRESS_POOL_PORT=9200
EGRESS_POOL_URL=http://127.0.0.1:9200
BUN_BIN=$BUN_BIN
HERMES_CONFIG=$HOME/.hermes/config.yaml
HERMES_RELAY_DEBUG=0
EOF
fi
# The env file has no secrets, but keep it out of world-read anyway.
sudo chown "root:$(id -gn "$USER")" "$ETC_DIR/egress.env" 2>/dev/null || true
sudo chmod 0640 "$ETC_DIR/egress.env" 2>/dev/null || true

python3 - "$SLOTS" <<'PY' | sudo tee "$ETC_DIR/sources.json" >/dev/null
import json, sys
slots = int(sys.argv[1])
print(json.dumps([
    {"name": "vpngate" if i == 0 else f"vpngate{i+1}",
     "relay": f"http://127.0.0.1:{9120 + i}", "priority": 0}
    for i in range(slots)
], indent=2))
PY
sudo chown "root:$(id -gn "$USER")" "$ETC_DIR/sources.json" 2>/dev/null || true
sudo chmod 0640 "$ETC_DIR/sources.json" 2>/dev/null || true

# ---------- systemd units ----------
sudo install -m 0644 "$HERE/systemd/system/hermes-vpngate-tunnel@.service" \
  /etc/systemd/system/hermes-vpngate-tunnel@.service
sudo systemctl daemon-reload

install -d "$HOME/.config/systemd/user"
install -m 0644 "$HERE"/systemd/user/*.service \
  "$HERE"/systemd/user/*.timer "$HOME/.config/systemd/user/"
install -d "$HOME/.config/systemd/user/hermes-opencode-forwarder.service.d"
install -m 0644 "$HERE/systemd/user/hermes-opencode-forwarder.service.d/egress-vpn.conf" \
  "$HOME/.config/systemd/user/hermes-opencode-forwarder.service.d/egress-vpn.conf"
systemctl --user daemon-reload

sudo loginctl enable-linger "$USER" 2>/dev/null || true

if [[ "$NO_START" == "1" ]]; then
  echo "Installed. Start with:"
  for ((i = 0; i < SLOTS; i++)); do
    echo "  sudo systemctl enable --now hermes-vpngate-tunnel@$i"
    echo "  systemctl --user enable --now hermes-egress-vpngate-relay@$i hermes-vpngate-recovery@$i.timer"
  done
  echo "  systemctl --user enable --now hermes-egress-pool hermes-egress-watchdog.timer"
  exit 0
fi

# ---------- start ----------
for ((i = 0; i < SLOTS; i++)); do
  sudo systemctl enable --now "hermes-vpngate-tunnel@$i.service"
  systemctl --user enable --now "hermes-egress-vpngate-relay@$i.service"
done

echo "Waiting for VPNGate relays (up to 240s; first connect downloads the server list)..."
ready=0
for _ in $(seq 1 120); do
  ready=1
  for ((i = 0; i < SLOTS; i++)); do
    port=$((9120 + i))
    code="$(curl -sS -m 3 -o /dev/null -w '%{http_code}' \
      "http://127.0.0.1:${port}/zen/v1/models" \
      -H 'Authorization: Bearer public' 2>/dev/null || echo 000)"
    [[ "$code" == "200" ]] || ready=0
  done
  ((ready)) && break
  sleep 2
done

systemctl --user enable --now hermes-egress-pool.service
for ((i = 0; i < SLOTS; i++)); do
  systemctl --user enable --now "hermes-vpngate-recovery@$i.timer"
done
systemctl --user enable --now hermes-egress-watchdog.timer

if systemctl --user cat hermes-opencode-forwarder.service >/dev/null 2>&1; then
  systemctl --user restart hermes-opencode-forwarder.service || true
fi

echo
hermes-egress status || true
echo
if ((ready)); then
  echo "OK: VPN relays are answering /models."
else
  echo "WARN: relays are not ready yet; run 'hermes-egress status' and check the logs."
  echo "      sudo journalctl -u hermes-vpngate-tunnel@0 -n 100 --no-pager"
fi
echo "Next: send one short message to Hermes to verify the Zen lane."
